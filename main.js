function displayRecipe(recipe) {
    //* ================= BASIC INFO =================

    document.getElementById("recipeImage").src = recipe.image;

    document.getElementById("recipeImage").alt = recipe.title;

    document.getElementById("recipeTitle").textContent = recipe.title;

    document.getElementById("recipeDescription").textContent =
        recipe.description;

    document.getElementById("difficulty").textContent =
        recipe.difficulty;

    document.getElementById("category").textContent =
        recipe.category;

    //* ================= RATING =================

    document.getElementById("rating").textContent =
        recipe.rating;

    document.getElementById("reviews").textContent =
        recipe.reviews;

    //* ================= TIME =================

    document.getElementById("prepTime").textContent =
        recipe.prepTime;

    document.getElementById("cookTime").textContent =
        recipe.cookTime;

    document.getElementById("servings").textContent =
        recipe.servings;

    //* ================= NUTRITION =================

    document.getElementById("calories").textContent =
        recipe.nutrition.calories;

    document.getElementById("protein").textContent =
        recipe.nutrition.protein;

    document.getElementById("carbs").textContent =
        recipe.nutrition.carbs;

    document.getElementById("fat").textContent =
        recipe.nutrition.fat;

    document.getElementById("fiber").textContent =
        recipe.nutrition.fiber;

    document.getElementById("sodium").textContent =
        recipe.nutrition.sodium;

    //* ================= INGREDIENTS =================

    ingredientsList.innerHTML = "";

    for (var i = 0; i < recipe.ingredients.length; i++) {

        ingredientsList.innerHTML += `
            <div class="ingredient">

                <span>${i + 1}</span>

                <p>${recipe.ingredients[i]}</p>

            </div>
        `;

    }

    //* ================= INSTRUCTIONS =================

    instructionsList.innerHTML = "";

    for (var i = 0; i < recipe.instructions.length; i++) {

        instructionsList.innerHTML += `
            <div class="ingredient">

                <span>${i + 1}</span>

                <p>${recipe.instructions[i]}</p>

            </div>
        `;

    }

    //* ================= CHEF'S TIPS =================

    tipsList.innerHTML = "";

    for (var i = 0; i < recipe.tips.length; i++) {

        tipsList.innerHTML += `
            <div class="tip-item">

                <div class="tip-icon">
                    <i class="fa-solid fa-check"></i>
                </div>

                <p>${recipe.tips[i]}</p>

            </div>
        `;

    }

}

